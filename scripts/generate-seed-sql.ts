/** SQL string literal with proper escaping. */
function sqlStr(value: string | null | undefined): string {
  if (value === null || value === undefined) return "NULL";
  return `'${value.replaceAll("'", "''")}'`;
}

function sqlBool(value: boolean | undefined, fallback = false): string {
  return (value ?? fallback) ? "1" : "0";
}

function sqlInt(value: number | null | undefined, fallback: number | null = null): string {
  if (value === null || value === undefined) {
    return fallback === null ? "NULL" : String(fallback);
  }
  return String(value);
}

/** Mirrors src/lib/auth.ts scrypt scheme: `salt:hash` (hex). */
function hashPassword(password: string): string {
  const salt = crypto.randomBytes(16).toString("hex");
  const hash = crypto.scryptSync(password, salt, 64).toString("hex");
  return `${salt}:${hash}`;
}

function valueList(values: string[]): string {
  return `(${values.join(", ")})`;
}

