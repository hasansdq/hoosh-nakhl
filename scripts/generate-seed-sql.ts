function settingsSql(
  fileName: string,
  header: string,
  values: { key: string; group: string; value: Row }[],
): void {
  const out = [
    `-- ${header}`,
    "-- Generated by scripts/generate-seed-sql.ts — INSERT OR IGNORE (never clobbers live admin settings).",
    "",
    ...values.map(
      (g) =>
        `INSERT OR IGNORE INTO "Setting" ("id", "key", "value", "group", "updatedAt") VALUES ${valueList([
          sqlStr(`setting-${g.key}`),
          sqlStr(g.key),
          sqlStr(JSON.stringify(g.value)),
          sqlStr(g.group),
          "CURRENT_TIMESTAMP",
        ])};`,
    ),
  ];
  writeFileSync(fileName, `${out.join("\n")}\n`, "utf8");
}

