#!/usr/bin/env bash
# =============================================================================
# Nakhl Restaurant — به‌روزرسانی بدون از دست رفتن داده‌ها (Docker / VPS)
# -----------------------------------------------------------------------------
# اجرا از ریشهٔ پروژه:   bash docker/update.sh
#
# پنج گام زمان‌دار (هر سه قانون طلایی رعایت می‌شود):
#  ۱. بررسی وضعیت فعلی (docker/compose/.env + حافظه/دیسک + رجیستری)
#  ۲. بک‌اپ لحظه‌ای از دیتابیس قبل از هر کاری (VACUUM INTO — سازگار آنلاین)
#  ۳. ساخت ایمیج جدید — با «ضربان‌سنج»: هر ۳۰ ثانیه یک خط وضعیت (زمان
#     سپری‌شده + گام جاری BuildKit)؛ قطع‌شدن خروجی = هشدار + علت‌یابی.
#     مرحلهٔ TypeScript روی سرورهای کند چند دقیقه بی‌خروجی و طبیعی است —
#     خطوط «[nakhl] … (cpu busy)» هر ۶۰ ثانیه نشانهٔ زنده بودن‌اند.
#  ۴. تعویض کانتینر (volume باقی می‌ماند — down -v هرگز) + اندازه‌گیری
#     «پنجرهٔ تعویض» (تنها بازه‌ای که ممکن است کاربر تأخیر ببیند)
#  ۵. جمع‌بندی + پاک‌سازی ایمیج‌های بلااستفاده + جدول زمان‌ها
#
# اگر بیلد شکست بخورد: کانتینر فعلی دست‌نخورده به سرویس‌دهی ادامه می‌دهد،
# بک‌اپ گام ۲ موجود است و علت به‌صورت خودکار تشخیص داده می‌شود (شبکه /
# کمبود حافظه OOM / خطای TypeScript) و لاگ کامل در /tmp نگه داشته می‌شود.
#
# نکتهٔ شبکه: Dockerfile عمداً بدون directive «# syntax=…» نوشته شده و بیلد
# برای خودش به docker.io وصل نمی‌شود (ایمیج‌های پایه از کش محلی مصرف می‌شوند).
# لایهٔ وابستگی‌های رانتایم هم فقط با تغییر lockfile دوباره ساخته می‌شود —
# آپدیت‌های معمول کد، بدون دانلود پکیج انجام می‌شوند.
#
# تنظیم ریز‌تر پایش (ثانیه، اختیاری):
#   NAKHL_BUILD_TICK=30   فاصلهٔ خط‌های تایمر (پیش‌فرض ۳۰)
#   NAKHL_STALL_WARN=240  آستانهٔ هشدار «بی‌خروجی» (پیش‌فرض ۲۴۰)
#   NAKHL_STALL_ALERT=900 آستانهٔ هشدار جدی + علت‌یابی (پیش‌فرض ۹۰۰)
# =============================================================================
set -euo pipefail

cd "$(dirname "$0")/.."

source docker/lib.sh
trap cleanup EXIT
trap 'exit 130' INT TERM

bold "═══ رستوران نخل — به‌روزرسانی ═══"
printf '  \033[2m%s\033[0m\n' "$(date '+%Y-%m-%d %H:%M:%S')"

# ═══════════ گام ۱: بررسی وضعیت فعلی ═══════════
ph "بررسی وضعیت فعلی" "۱" "۵"

command -v docker >/dev/null 2>&1 || { err "docker نصب نیست"; exit 1; }
docker compose version >/dev/null 2>&1 || { err "«docker compose v2» موجود نیست"; exit 1; }
if [ ! -f .env ]; then
  err "فایل .env یافت نشد — ابتدا: cp docker/env.example .env و مقادیر را تنظیم کنید"
  exit 1
fi

CURRENT_STATE="$(docker inspect --format '{{.State.Health.Status}}' nakhl-app 2>/dev/null || echo "راه‌اندازی‌نشده")"
ok "وضعیت کانتینر فعلی: ${CURRENT_STATE}"

PORT="$(grep -E '^NAKHL_PORT=' .env | cut -d= -f2 || true)"
PORT="${PORT:-8080}"

sys_preflight
net_preflight

ph_done

# ═══════════ گام ۲: بک‌اپ دیتابیس ═══════════
ph "بک‌اپ دیتابیس" "۲" "۵"

# قانون طلایی: قبل از هر تغییری snapshot — backup.sh برای exec داخل کانتینر
# به کانتینرِ در حال اجرا نیاز دارد؛ اگر بالانده، فقط پیام می‌دهیم.
if [ "$CURRENT_STATE" = "راه‌اندازی‌نشده" ]; then
  warn "کانتینر فعلی در حال اجرا نیست — بک‌اپ داخل volume انجام نشد"
  echo  "    اگر قبلاً استقرار موفق داشته‌اید: docker compose start app و دوباره تلاش کنید"
  echo  "    اگر این اولین استقرار است: bash docker/deploy.sh مناسب‌تر است"
else
  if ! bash docker/backup.sh; then
    err "بک‌اپ پیش از به‌روزرسانی نشست — برای ایمنی داده، ادامه نمی‌دهیم"
    echo  "    (کانتینر فعلی دست‌نخورده است؛ برای رفع: docker compose logs --tail=50 app)"
    exit 1
  fi
fi

ph_done

# ═══════════ گام ۳: ساخت ایمیج جدید ═══════════
ph "ساخت ایمیج جدید" "۳" "۵"

build_image
if [ "$BUILD_RC" -ne 0 ]; then
  diagnose_build_failure "هیچ چیزی تغییر نکرده است"
  echo  "    • کانتینر فعلی همچنان در حال سرویس‌دهی است (نسخهٔ قبلی)"
  echo  "    • بک‌اپ گام ۲ گرفته شده است (docker/restore.sh در صورت نیاز)"
  STATE_NOW="$(docker inspect --format '{{.State.Health.Status}}' nakhl-app 2>/dev/null || echo "?")"
  if [ "$STATE_NOW" = "healthy" ]; then
    ok "وضعیت فعلی: کانتینر قبلی healthy — سرویس‌دهی ادامه دارد"
  fi
  exit 1
fi

ph_done

# ═══════════ گام ۴: تعویض کانتینر ═══════════
ph "تعویض کانتینر" "۴" "۵"

SWAP_T0="$(now_s)"
docker compose up -d
wait_healthy 120 || exit 1
SWAP_WINDOW=$(( $(now_s) - SWAP_T0 ))
ok "پنجرهٔ تعویض نسخه: ${SWAP_WINDOW}s (تنها بازهٔ ممکن تأخیر برای کاربران)"
http_health "$PORT"

ph_done

# ═══════════ گام ۵: جمع‌بندی ═══════════
ph "جمع‌بندی" "۵" "۵"

# پاک‌سازی ایمیج‌های قدیمی بی‌استفاده (volume ها را هرگز لمس نمی‌کند)
docker image prune -f >/dev/null 2>&1 && ok "ایمیج‌های بلااستفاده پاک شدند" || true

summary

echo
bold "═══ به‌روزرسانی کامل شد — داده‌ها دست‌نخورده ═══"
docker compose ps

ph_done
